"""
Sanity check: Optimist and Skeptic debate a topic for 2-3 rounds
(ending early if the Skeptic comes to agree), then a Judge agent reads the
whole exchange and delivers a final, cleaned-up answer.

Test Generated by GenAI
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from agents import Agent                                   # noqa: E402
from models import AnthropicClient, OpenAIClient            # noqa: E402
from orchestration import AdaptiveDebate, Orchestrator  # noqa: E402
from state import Transcript                                # noqa: E402


def build_clients():
    clients = []
    for cls in (AnthropicClient, OpenAIClient):
        try:
            clients.append(cls())
        except Exception as e:
            print(f"[skip] {cls.__name__}: {e}")
    if not clients:
        raise SystemExit("No API keys set - need at least one provider.")
    if len(clients) == 1:
        clients = [clients[0]] * 3  # reuse the one model for all three roles
    else:
        clients.append(clients[0])  # judge reuses the first provider
    return clients


OPTIMIST_PERSONA = (
    "You argue that the idea under discussion is promising and highlight its upsides. "
    "Be persuasive but honest; concede a point if the Skeptic raises something genuinely strong."
)

SKEPTIC_PERSONA = (
    "You challenge weak assumptions and point out risks and failure modes in the Optimist's "
    "argument. Be rigorous but fair - if the Optimist addresses your concerns well, say so.\n\n"
    "IMPORTANT: Always start your reply with exactly one line, before anything else:\n"
    "AGREEMENT: YES   (if you now substantially agree with the Optimist's position)\n"
    "AGREEMENT: NO    (if you still have unresolved objections)\n"
    "Then continue with your actual response on the following lines."
)

JUDGE_PERSONA = (
    "You are a neutral judge/moderator for a debate. You did not participate in the discussion. "
    "Read the full exchange between Optimist and Skeptic and produce:\n"
    "1) A brief, neutral summary of the discussion and where the two participants agreed or disagreed.\n"
    "2) A clear, decisive final answer to the original topic, synthesizing the strongest reasoning "
    "from both sides. This final answer is what the user actually sees as the outcome - make it useful "
    "on its own, without requiring them to have read the debate."
)


def main():
    opt_client, skep_client, judge_client = build_clients()

    optimist = Agent("Optimist", OPTIMIST_PERSONA, opt_client)
    skeptic = Agent("Skeptic", SKEPTIC_PERSONA, skep_client)
    judge = Agent("Judge", JUDGE_PERSONA, judge_client)

    algorithm = AdaptiveDebate(skeptic_name="Skeptic", min_rounds=2, max_rounds=3)
    transcript = Transcript(log_path="results/debate_001.jsonl")
    orchestrator = Orchestrator([optimist, skeptic], algorithm, judge, transcript)

    topic = "Is 1+1 = 2?"
    orchestrator.run(topic)


if __name__ == "__main__":
    main()